"""
音声認識が返す漢字・混在表記を辞書に追加する
speech-to-text はひらがな/カタカナだけでなく漢字も返すので両方必要
"""

with open('app.js', 'r', encoding='utf-8') as f:
    src = f.read()

# 追加するエントリ（既存辞書の末尾 ].sort(...) の直前に挿入）
additions = """
  // 漢字表記（音声認識が返すパターン）
  'ご飯','お米','御飯',
  'お茶','緑茶','麦茶','紅茶','ほうじ茶',
  'お酒','日本酒','焼酎',
  'お味噌','お醤油',
  'お豆腐',
  '林檎','蜜柑','葡萄','苺','桃','梨','柿','栗',
  '玉葱','人参','大根','牛蒡','蓮根','南瓜','茄子','胡瓜',
  '白菜','小松菜','春菊','水菜','三つ葉','生姜','大蒜',
  '鶏卵','玉子','玉卵',
  '豚肉','牛肉','鶏肉','挽肉','合挽',
  '鮭','鯖','鰯','鯵','鰤','鰹','鮪',
  '海老','蛸','烏賊',
  '醤油','味噌','砂糖','胡椒','唐辛子',
  '牛乳','豆乳',
  '蕎麦','素麺','冷麦',
  'トイレットペーパー','ティッシュペーパー',
"""

# ].sort の直前に挿入
target = '].sort((a, b) => b.length - a.length);'
if target in src:
    src = src.replace(target, additions + target)
    with open('app.js', 'w', encoding='utf-8') as f:
        f.write(src)
    print('✅ 辞書に漢字表記を追加しました')
else:
    print('❌ 挿入箇所が見つかりません')
